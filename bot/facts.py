CATEGORY_LABELS = {
    "religious": "دينية 🕌",
    "general": "عامة 🌍",
    "both": "متنوعة ✨",
}


def next_fact(user_id):
    """يعيد (تسمية_النوع, نص_المعلومة) التالية للمستخدم دون تكرار حتى اكتمال الدورة."""
    from . import db as _db
    cat = _db.get_fact_category(user_id)
    pool = FACTS_MIXED if cat == "both" else FACTS[cat]
    idx = _db.get_fact_offset(user_id, cat) % len(pool)
    text = pool[idx]
    _db.set_fact_offset(user_id, cat, idx + 1)
    return CATEGORY_LABELS[cat], text
